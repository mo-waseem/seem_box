import { readFile, writeFile } from "node:fs/promises";
import { parseEnv } from "node:util";
import { pathToFileURL } from "node:url";

export function extensionConfig(value = "http://localhost:3000") {
  let url;
  try {
    url = new URL(value);
  } catch {
    throw new Error("SEEM_BOX_EXTENSION_URL must be an HTTP(S) origin, such as http://localhost:3000.");
  }
  if (!["http:", "https:"].includes(url.protocol) || url.hostname.includes("*") || url.username || url.password || url.pathname !== "/" || url.search || url.hash) {
    throw new Error("SEEM_BOX_EXTENSION_URL must be an HTTP(S) origin without credentials, a path, query, or fragment.");
  }
  return {
    origin: url.origin,
    // Chrome match patterns do not restrict ports; the request URL still does.
    permission: `${url.protocol}//${url.hostname}/*`,
    script: `// Generated by npm run extension:configure. Contains only the public server URL.\nglobalThis.SEEM_BOX_EXTENSION_URL = ${JSON.stringify(url.origin)};\n`,
  };
}

export async function configureExtension(root, env = process.env) {
  const values = {};
  for (const name of [".env", ".env.local"]) {
    try {
      Object.assign(values, parseEnv(await readFile(new URL(name, root), "utf8")));
    } catch (error) {
      if (error.code !== "ENOENT") throw error;
    }
  }
  const config = extensionConfig(env.SEEM_BOX_EXTENSION_URL ?? values.SEEM_BOX_EXTENSION_URL);
  const manifestPath = new URL("extension/manifest.json", root);
  const manifest = JSON.parse(await readFile(manifestPath, "utf8"));
  manifest.host_permissions = ["https://www.youtube.com/*", config.permission];
  await writeFile(new URL("extension/config.js", root), config.script);
  await writeFile(manifestPath, `${JSON.stringify(manifest, null, 2)}\n`);
  return config.origin;
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  const origin = await configureExtension(new URL("../", import.meta.url));
  console.log(`Extension configured for ${origin}. Reload it at chrome://extensions, then refresh YouTube.`);
}
